async function main() {
  console.log(`Adding ${newIssues.length} new Ford issues across 8 models...`);

  let added = 0;
  let skipped = 0;

  for (const issue of newIssues) {
    try {
      const existing = await prisma.knownIssue.findUnique({ where: { id: issue.id } });
      if (existing) {
        console.log(`  SKIP (exists): ${issue.id}`);
        skipped++;
        continue;
      }

      await prisma.knownIssue.create({ data: issue });
      console.log(`  ADD: ${issue.id}`);
      added++;
    } catch (err) {
      console.error(`  ERROR: ${issue.id} — ${err.message}`);
    }
  }

  // Print summary by model
  const models = ['Escape', 'Edge', 'Maverick', 'Bronco Sport', 'F-250 Super Duty', 'Expedition', 'Focus', 'Mustang Mach-E'];
  console.log('\n--- Summary by model ---');
  for (const model of models) {
    const count = await prisma.knownIssue.count({ where: { make: 'Ford', model } });
    const addedForModel = newIssues.filter(i => i.model === model).length;
    console.log(`  ${model}: ${count} total (added ${addedForModel} this run)`);
  }

  const totalFord = await prisma.knownIssue.count({ where: { make: 'Ford' } });
  console.log(`\nTotal Ford issues in database: ${totalFord}`);
  console.log(`Added: ${added}, Skipped: ${skipped}`);

  await prisma.$disconnect();
  await pool.end();
}

main().catch(e => { console.error(e); process.exit(1); });
